//! The generated reference pages, `docs/keys.md` and the settings table in
//! `docs/config.md`, rendered from the same tables the binary runs on
//! (`task docs` writes them, `task docs:check` fails when they drift).
//! Everything comes from the built-in defaults, never from the user's config
//! or remembered state, so any machine generates the same bytes.

use std::fmt::Write as _;

use clap::ValueEnum;

use crate::config::{self, KEYS};
use crate::keys::{Action, Chord, Group, Keys};
use crate::state;

/// Opens every generated page or section; `task docs` splices
/// `docs/config.md` between this line and [`END`].
const BEGIN: &str = "<!-- generated by task docs: do not edit -->";
const END: &str = "<!-- end of generated section -->";

/// `docs/keys.md`.
pub(crate) fn keys() -> String {
    let keys = Keys::default();
    let mut out = String::new();
    let _ = writeln!(out, "{BEGIN}\n");
    out.push_str(KEYS_INTRO);
    for group in Group::ALL {
        let _ = writeln!(out, "\n### {}\n", group.title());
        out.push_str("| Action | Keys | Command panel | Description |\n|---|---|---|---|\n");
        for &action in Action::ALL.iter().filter(|a| a.group() == group) {
            let shown: Vec<String> = [
                (spans(keys.chords(false, action)), ""),
                (spans(keys.chords(true, action)), " in the tree"),
                (spans(keys.thread_chords(action)), " on a thread"),
                (spans(keys.conflict_chords(action)), " in a conflicted file"),
            ]
            .into_iter()
            .filter(|(keys, _)| !keys.is_empty())
            .map(|(keys, table)| format!("{keys}{table}"))
            .collect();
            let shown = shown.join("; ");
            let leader = spans(
                keys.leader_entries()
                    .iter()
                    .filter(|(_, a)| *a == action)
                    .map(|&(c, _)| c),
            );
            let _ = writeln!(
                out,
                "| `{}` | {} | {} | {} |",
                action.name(),
                shown,
                leader,
                cell(&capitalize(action.doc()))
            );
        }
    }
    section(
        &mut out,
        "\n## In the tree\n\nWhile the file tree has focus, these keys come first; \
         every other key does what it does in the diff.\n\n",
        |action| spans(keys.chords(true, action)),
    );
    section(
        &mut out,
        "\n## On a thread\n\nWhile a comment thread is focused in the diff, or selected in the \
         comments panel, these keys come first and act on it; every other key does what it \
         does without one. `esc` takes the focus off the thread.\n\n",
        |action| spans(keys.thread_chords(action)),
    );
    section(
        &mut out,
        "\n## In a conflicted file\n\nWhile the file at the cursor has conflicts to resolve, \
         these keys come after a thread's and before every other; the rest do what they do \
         elsewhere. While a search goes on, `n` and `N` keep stepping through its matches, \
         and past the last conflict that way they go on to the next change.\n\n",
        |action| spans(keys.conflict_chords(action)),
    );
    out.push_str(
        "\n## Command panel\n\n`space` opens the panel as a quick popup of what applies to \
         what you're on; `space` or `tab` again shows the whole panel. These keys run its \
         entries from the popup and from any tab; within a group, the panel lists them in this \
         order. On a setting with values \
         (`Layout ‹ auto ›`), `h`/`l` and `left`/`right` step back and forward; on other rows \
         they do nothing, so a `leader:h` or `leader:l` binding never runs, and `tab` and \
         `shift+tab` switch tabs. `enter` on Theme opens the theme list.\n\n\
         | Key | Entry | Action |\n|---|---|---|\n",
    );
    for &(chord, action) in keys.leader_entries() {
        let _ = writeln!(
            out,
            "| {} | {} | `{}` |",
            span(chord),
            cell(action.title()),
            action.name()
        );
    }
    out
}

/// `intro`, then a table of every action `keys` gives keys.
fn section(out: &mut String, intro: &str, keys: impl Fn(Action) -> String) {
    out.push_str(intro);
    out.push_str("| Keys | Action | Description |\n|---|---|---|\n");
    for &action in Action::ALL {
        let shown = keys(action);
        if !shown.is_empty() {
            let _ = writeln!(
                out,
                "| {shown} | `{}` | {} |",
                action.name(),
                cell(&capitalize(action.doc()))
            );
        }
    }
}

const KEYS_INTRO: &str = "\
# Keys

Every action in the viewer with its default keys. In the viewer, `?` lists the keys in effect, \
your own bindings included, and `space` opens the command panel. [viewer.md](viewer.md) \
covers what the keys act on.

## Rebinding

`keybind` lines in the [config file](config.md) change the bindings. The line can repeat; \
later lines win.

```
# Bind a key to an action
keybind = ctrl+d=page_down
# Free a key
keybind = q=unbind
# Only while the file tree has focus
keybind = tree:x=mark_viewed
# Only on a focused comment thread
keybind = thread:R=reply
# Only in a file with conflicts to resolve
keybind = conflict:O=keep_current
# A key in the command panel
keybind = leader:z=toggle_wrap
```

- **Keys:** a character as typed (`n`, `N`, `<`, `?`) or a name: `space`, `enter`, `tab`, \
`shift+tab`, `esc`, `backspace`, `up`, `down`, `left`, `right`, `home`, `end`, `page_up`, \
`page_down`, `insert`, `delete`, `f1` to `f12`. `ctrl+` and `alt+` go before the key. \
`shift+` works with letters (`shift+n` is `N`) and `tab`; for other characters, bind the \
shifted character itself.
- **Tables:** there are five. Keys pressed while the tree has focus look in the tree's \
table (`tree:`) first, then in the main one. Keys pressed on a comment thread look in the \
thread's table (`thread:`) first, then, in a file with conflicts to resolve, in the \
conflict's (`conflict:`). The command panel has its own table (`leader:`); rebinding a key \
there keeps the entry's place in the panel. By default a panel key the main table binds \
too does the same thing there.
- **Fallbacks:** a key pressed with `alt` or `shift` that has no binding of its own acts \
as the plain key.
- **`esc`:** it always backs out first (closes a panel, ends a search or filter, cancels \
a selection, leaves the tree). Bound to another action, as in `keybind = esc=quit`, it \
runs that action only when there's nothing left to back out of.
- **Mistakes:** a line with an unknown key or action is skipped with a warning that \
suggests the closest name.
- **Checking:** `dffy config` ends with the `keybind` lines that turn the defaults into \
your bindings, and `dffy config --default` lists every action with its keys.

## Actions
";

/// The settings table of `docs/config.md`, between its markers.
pub(crate) fn config() -> String {
    let mut out = String::new();
    let _ = writeln!(out, "{BEGIN}\n");
    out.push_str("| Key | Default | Values | Remembered | Description |\n|---|---|---|---|---|\n");
    for key in KEYS {
        let default = if key.default.is_empty() {
            "empty".to_owned()
        } else {
            format!("`{}`", key.default)
        };
        let remembered = if state::REMEMBERED.contains(&key.name) {
            "yes"
        } else {
            ""
        };
        let _ = writeln!(
            out,
            "| `{}` | {default} | {} | {remembered} | {} |",
            key.name,
            values(key.name),
            cell(key.doc)
        );
    }
    let _ = writeln!(out, "\n{END}");
    out
}

/// What `key` accepts, as [`config::Config::set`] parses it. Empty for a
/// key not listed here, which the tests catch.
fn values(key: &str) -> String {
    fn choices<T: ValueEnum>() -> String {
        T::value_variants()
            .iter()
            .map(|v| format!("`{}`", config::choice_name(v)))
            .collect::<Vec<_>>()
            .join(", ")
    }
    match key {
        "color" => choices::<config::ColorWhen>(),
        "paging" => choices::<config::Paging>(),
        "view" => choices::<config::View>(),
        "indicators" => choices::<config::Indicators>(),
        "background" => choices::<config::Background>(),
        "default-diff" => choices::<config::DefaultDiff>(),
        "tree" => choices::<config::TreeMode>(),
        "status-bar" => choices::<config::StatusBar>(),
        "modified-lines" => choices::<config::ModifiedLines>(),
        "wrap"
        | "ignore-all-space"
        | "ignore-space-change"
        | "renames"
        | "highlight"
        | "syntax-diff"
        | "rendered"
        | "watch"
        | "line-numbers"
        | "hunk-headers"
        | "copy-decorations"
        | "remember"
        | "tips"
        | "mouse"
        | "cache" => "`true`, `false`".to_owned(),
        "pager" => "a shell command".to_owned(),
        "theme" => "a theme name".to_owned(),
        "render" => "`extension:name` pairs, space-separated".to_owned(),
        "review" => "a plugin name, `auto`, `none`, or empty".to_owned(),
        "agent" => "`claude`, `codex`, `pi`, a command, or empty".to_owned(),
        "split-min-width" => "columns".to_owned(),
        "tab-width" => "columns, at least 1".to_owned(),
        "context" => "lines, or `full`".to_owned(),
        "tree-width" => "columns, or `auto`".to_owned(),
        "cache-size" => "bytes, or a number with `K`, `M` or `G`".to_owned(),
        _ => String::new(),
    }
}

fn spans(chords: impl Iterator<Item = Chord>) -> String {
    chords.map(span).collect::<Vec<_>>().join(" ")
}

fn span(chord: Chord) -> String {
    format!("`{}`", cell(&chord.name()))
}

/// Text made safe for a table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

fn capitalize(text: &str) -> String {
    let mut chars = text.chars();
    chars.next().map_or_else(String::new, |first| {
        first.to_uppercase().chain(chars).collect()
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_config_key_lists_values_it_accepts() {
        for key in KEYS {
            let listed = values(key.name);
            assert!(!listed.is_empty(), "{} has no values listed", key.name);
            let choices: Option<Vec<&str>> = listed
                .split(", ")
                .map(|v| {
                    v.strip_prefix('`')?
                        .strip_suffix('`')
                        .filter(|v| !v.contains('`'))
                })
                .collect();
            for value in choices.into_iter().flatten() {
                let mut config = config::Config::default();
                assert_eq!(
                    config.set(key.name, value),
                    Ok(()),
                    "{} = {value}",
                    key.name
                );
            }
        }
    }
}
